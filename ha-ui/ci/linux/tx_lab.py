#!/usr/bin/env python3
"""Stage B transaction lab (Linux only; no root, no network, no VPS).

Runs the real Bash transaction code from ``lib/client-management.sh`` plus the
exact detached worker text generated by ``ha_ui.core.remote`` and injects
process-level failures:

  1. committed transaction: check/backup/replace/reload/health, new bytes;
  2. health failure -> proven rollback (bytes restored, exact sentence, phases);
  3. rollback whose service recovery is unconfirmed -> rollback_manual;
  4. SIGKILL during ``reload``: journal stops at reload, new bytes are live,
     the canonical lock is released, no terminal record exists;
  5. concurrent writer: refused by the canonical client lock;
  6. detached worker survives the death of the process that started it
     (SSH-disconnect analogue);
  7. detached worker survives a closed stdout consumer;
  8. pre-commit watchdog stops a hung pre-``replace`` menu and leaves no
     terminal success;
  9. read-only status query distinguishes terminal / absent states.

Exits 0 only when every scenario holds. Windows skips with a clear message.
"""

from __future__ import annotations

import json
import os
import shutil
import signal
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LIB = ROOT / "lib" / "client-management.sh"
sys.path.insert(0, str(ROOT / "ha-ui"))

from ha_ui.core import remote  # noqa: E402

PASSED = 0

SYSTEMCTL_STUB = r'''#!/bin/bash
case "$1" in
  is-active)
    n=$(cat "$STUB_COUNTER" 2>/dev/null || echo 0); n=$((n + 1))
    echo "$n" > "$STUB_COUNTER"
    if [ "$n" -eq 2 ]; then exit "${STUB_ACTIVE2_RC:-0}"; fi
    exit "${STUB_ACTIVE1_RC:-0}" ;;
  reload)
    sleep "${STUB_RELOAD_SLEEP:-0}"
    exit "${STUB_RELOAD_RC:-0}" ;;
esac
exit 0
'''

PGREP_STUB = "#!/bin/bash\nexit 1\n"
SINGBOX_STUB = '#!/bin/bash\nexit "${STUB_CHECK_RC:-0}"\n'

COMMIT_SCENARIO = r'''#!/bin/bash
set -u
. "@@LIB@@"
info() { :; }
warning() { printf 'WARN %s\n' "$*" >&2; }
ha_ui_lab_journal() {
  printf '%s\t%s\t%s\n' "$1" "$(date +%s)" "${2:-}" >> "$HA_UI_LAB_JOURNAL"
}
export CM_TX_JOURNAL_HOOK=ha_ui_lab_journal
export SB_SERVER_CONFIG="@@LIVE@@"
export SB_LOCK_FILE="@@LOCK@@"
export SB_SING_BOX_BIN="@@STUBDIR@@/sing-box"
export PATH="@@STUBDIR@@:$PATH"
lab_commit() { commit_server_config "$1" "lab"; }
with_client_lock lab_commit "@@CANDIDATE@@"
'''

INSTALLER = r'''#!/bin/bash
set -u
. "@@LIB@@"
cm_tx_journal_phase check
cm_tx_journal_phase backup
cm_tx_journal_phase replace
sleep "@@SLEEP@@"
cm_tx_journal_phase reload
cm_tx_journal_phase health
printf '配置已提交并重载成功\n'
printf "客户端 '@@NAME@@' 已同时添加到 Reality 与 HY2\n"
'''

INSTALLER_HANG = "#!/bin/bash\nsleep 30\n"


def ok(message: str) -> None:
    global PASSED
    PASSED += 1
    print("PASS: %s" % message, flush=True)


def fail(message: str) -> None:
    print("FAIL: %s" % message, flush=True)
    raise SystemExit(1)


def write(path: Path, text: str, mode: int = 0o600) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    path.chmod(mode)
    return path


def config(users: list[str]) -> str:
    reality = [
        {"name": name,
         "uuid": "11111111-1111-1111-1111-%012d" % index,
         "flow": "xtls-rprx-vision"}
        for index, name in enumerate(users)
    ]
    hy2 = [{"name": name, "password": "pw-%s" % name} for name in users]
    return json.dumps({"inbounds": [
        {"tag": "vless-in", "listen_port": 443, "users": reality},
        {"tag": "hy2-in", "listen_port": 8443, "users": hy2},
    ]}, indent=2)


def stubs(work: Path) -> Path:
    stubdir = work / "stubs"
    write(stubdir / "systemctl", SYSTEMCTL_STUB, 0o755)
    write(stubdir / "pgrep", PGREP_STUB, 0o755)
    write(stubdir / "sing-box", SINGBOX_STUB, 0o755)
    return stubdir


def commit_scenario(work: Path, live_text: str, candidate_text: str,
                    env_overrides: dict[str, str],
                    kill_on_phase: str | None = None):
    stubdir = stubs(work)
    live = write(work / "live.json", live_text)
    candidate = write(work / "candidate.json", candidate_text)
    script = (COMMIT_SCENARIO.replace("@@LIB@@", str(LIB))
              .replace("@@LIVE@@", str(live))
              .replace("@@LOCK@@", str(work / "lock"))
              .replace("@@STUBDIR@@", str(stubdir))
              .replace("@@CANDIDATE@@", str(candidate)))
    runner = write(work / "run.sh", script, 0o755)
    env = dict(os.environ)
    env.update(env_overrides)
    env["STUB_COUNTER"] = str(work / "counter")
    if kill_on_phase is None:
        proc = subprocess.run(["bash", str(runner)], capture_output=True,
                              text=True, env=env, timeout=120)
        return proc.returncode, proc.stdout + proc.stderr, live
    proc = subprocess.Popen(["bash", str(runner)], stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, text=True, env=env)
    journal = work / "phases"
    deadline = time.time() + 30
    while time.time() < deadline:
        if journal.exists() and kill_on_phase in journal.read_text():
            time.sleep(0.1)
            os.kill(proc.pid, signal.SIGKILL)
            break
        if proc.poll() is not None:
            break
        time.sleep(0.02)
    try:
        out = proc.communicate(timeout=10)[0] or ""
    except subprocess.TimeoutExpired:
        proc.kill()
        out = ""
    return -9, out, live


def scenario_success(work: Path) -> None:
    rc, out, live = commit_scenario(
        work, config([]), config(["alpha"]),
        {"STUB_ACTIVE1_RC": "0", "STUB_ACTIVE2_RC": "0",
         "STUB_RELOAD_RC": "0", "STUB_CHECK_RC": "0"})
    if rc != 0:
        fail("success rc=%s out=%s" % (rc, out[-400:]))
    if "alpha" not in live.read_text():
        fail("success did not replace the live config")
    phases = (work / "phases").read_text()
    for phase in ("check", "backup", "replace", "reload", "health"):
        if phase not in phases:
            fail("missing phase %r" % phase)
    if "rollback" in phases:
        fail("success recorded a rollback")
    ok("committed transaction journals check/backup/replace/reload/health")


def scenario_health_rollback(work: Path) -> None:
    rc, out, live = commit_scenario(
        work, config([]), config(["alpha"]),
        {"STUB_ACTIVE1_RC": "0", "STUB_ACTIVE2_RC": "1",
         "STUB_RELOAD_RC": "0"})
    if rc == 0:
        fail("health failure reported success")
    if '"alpha"' in live.read_text():
        fail("health failure did not restore the pre-write bytes")
    if "rollback" not in (work / "phases").read_text():
        fail("health failure did not journal the rollback")
    if "已回滚并重新加载上一份配置" not in out:
        fail("proven-rollback sentence missing")
    ok("health failure restores bytes and journals a proven rollback")


def scenario_rollback_unconfirmed(work: Path) -> None:
    rc, out, live = commit_scenario(
        work, config([]), config(["alpha"]),
        {"STUB_ACTIVE1_RC": "0", "STUB_RELOAD_RC": "1"})
    if rc == 0:
        fail("unconfirmed rollback reported success")
    if '"alpha"' in live.read_text():
        fail("unconfirmed rollback did not restore the bytes")
    if "服务未能确认恢复" not in out:
        fail("unconfirmed-rollback sentence missing")
    ok("rollback with an unconfirmed service is reported as such")


def scenario_kill_during_reload(work: Path) -> None:
    _rc, _out, live = commit_scenario(
        work, config([]), config(["alpha"]),
        {"STUB_ACTIVE1_RC": "0", "STUB_RELOAD_SLEEP": "30"},
        kill_on_phase="reload")
    if '"alpha"' not in live.read_text():
        fail("kill scenario: replaced bytes were not live")
    phases = [line.split("\t", 1)[0]
              for line in (work / "phases").read_text().splitlines() if line]
    if phases[-1] != "reload":
        fail("kill scenario: journal last phase is %r" % (phases[-1:],))
    if "health" in phases:
        fail("kill scenario: health ran after the kill")
    probe = subprocess.run(["flock", "-n", str(work / "lock"), "true"],
                           capture_output=True)
    if probe.returncode != 0:
        fail("kill scenario: the canonical lock was not released")
    ok("SIGKILL during reload leaves new bytes + phase=reload + free lock")


def scenario_concurrent_writer(work: Path) -> None:
    stubdir = stubs(work)
    live = write(work / "live.json", config([]))
    script = (COMMIT_SCENARIO.replace("@@LIB@@", str(LIB))
              .replace("@@LIVE@@", str(live))
              .replace("@@LOCK@@", str(work / "lock"))
              .replace("@@STUBDIR@@", str(stubdir))
              .replace("@@CANDIDATE@@", str(write(work / "c1.json",
                                                  config(["alpha"])))))
    runner = write(work / "run.sh", script, 0o755)
    env = dict(os.environ)
    env.update({"STUB_COUNTER": str(work / "counter"),
                "STUB_RELOAD_SLEEP": "5"})
    first = subprocess.Popen(["bash", str(runner)], env=env,
                             stdout=subprocess.DEVNULL,
                             stderr=subprocess.DEVNULL)
    time.sleep(0.5)
    second = subprocess.run(["bash", str(runner)], env=env, timeout=60,
                            capture_output=True, text=True)
    first.wait(timeout=60)
    if second.returncode == 0:
        fail("concurrent writer was not refused")
    if "配置锁" not in (second.stdout + second.stderr):
        fail("concurrent writer failed without the canonical lock message")
    ok("concurrent writer is refused by the canonical client lock")


def make_tx(work: Path, tag: str, name: str) -> Path:
    tx = work / ("tx-" + tag)
    tx.mkdir(mode=0o700)
    txid = name + "-" + tag[0].lower() * 32
    text = remote._tx_env_text(txid).replace(
        remote.TX_ROOT + "/" + txid, str(tx))
    write(tx / "env.sh", text)
    write(tx / "in", "")
    return tx


def scenario_worker_survives_launcher(work: Path) -> None:
    tx = make_tx(work, "aaaa", "alpha")
    installer_dir = work / "inst1"
    write(installer_dir / "install.sh",
          INSTALLER.replace("@@LIB@@", str(LIB))
          .replace("@@SLEEP@@", "1.5").replace("@@NAME@@", "alpha"), 0o755)
    worker = write(work / "worker1.sh",
                   remote._tx_worker_script(precommit=10), 0o600)
    launcher = ("setsid bash %s haui_tx %s %s %s & echo $! > %s" % (
        worker, tx, installer_dir, int(time.time()), work / "pid1"))
    outer = subprocess.Popen(["bash", "-c", launcher], start_new_session=True)
    time.sleep(0.3)
    outer.kill()
    try:
        os.killpg(os.getpgid(outer.pid), signal.SIGKILL)
    except ProcessLookupError:
        pass
    deadline = time.time() + 20
    while time.time() < deadline and not (tx / "result").exists():
        time.sleep(0.05)
    if not (tx / "result").exists():
        fail("detached worker did not publish a result after launcher death")
    if "rc=0" not in (tx / "result").read_text():
        fail("detached worker reported a non-zero rc")
    if "replace" not in (tx / "phases").read_text():
        fail("detached worker never journaled replace")
    ok("detached worker survives the death of its launcher")


def scenario_worker_survives_closed_stdout(work: Path) -> None:
    tx = make_tx(work, "bbbb", "beta")
    installer_dir = work / "inst2"
    write(installer_dir / "install.sh",
          INSTALLER.replace("@@LIB@@", str(LIB))
          .replace("@@SLEEP@@", "1.0").replace("@@NAME@@", "beta"), 0o755)
    worker = write(work / "worker2.sh",
                   remote._tx_worker_script(precommit=10), 0o600)
    reader, writer = os.pipe()
    proc = subprocess.Popen(
        ["bash", str(worker), "haui_tx", str(tx), str(installer_dir),
         str(int(time.time()))],
        stdout=writer, stderr=writer, stdin=subprocess.DEVNULL,
        start_new_session=True)
    os.close(writer)
    os.close(reader)
    proc.wait(timeout=30)
    if not (tx / "result").exists():
        fail("worker without a stdout consumer published no result")
    ok("detached worker survives a closed stdout consumer")


def scenario_watchdog(work: Path) -> None:
    tx = make_tx(work, "cccc", "gamma")
    installer_dir = work / "inst3"
    write(installer_dir / "install.sh", INSTALLER_HANG, 0o755)
    worker = write(work / "worker3.sh",
                   remote._tx_worker_script(precommit=1), 0o600)
    subprocess.run(["bash", str(worker), "haui_tx", str(tx),
                    str(installer_dir), str(int(time.time()))],
                   timeout=40)
    if not (tx / "result").exists():
        fail("watchdog published no result")
    notes = (tx / "notes").read_text() if (tx / "notes").exists() else ""
    if "watchdog=precommit-timeout" not in notes:
        fail("watchdog note missing")
    phases = (tx / "phases").read_text() if (tx / "phases").exists() else ""
    if "replace" in phases:
        fail("watchdog killed after the replace boundary")
    out = status_text(tx, "gamma")
    status = remote._parse_tx_status(out)
    if status.success or status.committed:
        fail("watchdog outcome was reported as success")
    ok("pre-commit watchdog stops a hung menu and never claims success")


def status_text(tx: Path, name: str) -> str:
    script = ("tx=%s; " % tx) + remote._tx_status_body(name)
    return subprocess.run(["bash", "-c", script], capture_output=True,
                          text=True).stdout


def scenario_status_query(work: Path) -> None:
    tx = work / "tx-status"
    tx.mkdir(mode=0o700)
    write(tx / "phases", "check\t1\t/root/x.bak\nreplace\t2\t/root/x.bak\n")
    write(tx / "result", "rc=0\nfinished=3\n")
    write(tx / "pid", "999999\n")
    write(tx / "out",
          "配置已提交并重载成功\n"
          "客户端 'delta' 已同时添加到 Reality 与 HY2\n")
    status = remote._parse_tx_status(status_text(tx, "delta"))
    if not (status.terminal and status.committed and status.success):
        fail("terminal status was not parsed as a committed success")
    if status.running:
        fail("dead pid was reported as running")
    absent = remote._parse_tx_status("HAUI_TX_ABSENT=1\n")
    if not absent.absent:
        fail("absent marker was not parsed")
    ok("read-only status query distinguishes terminal and absent")


def main() -> int:
    if os.name != "posix" or shutil.which("flock") is None:
        print("SKIP: linux-only lab (needs bash/flock/setsid)")
        return 0
    work_root = Path(tempfile.mkdtemp(prefix="ha-ui-txlab-"))
    try:
        for name, scenario in (
                ("success", scenario_success),
                ("health-rollback", scenario_health_rollback),
                ("rollback-unconfirmed", scenario_rollback_unconfirmed),
                ("kill-during-reload", scenario_kill_during_reload),
                ("concurrent-writer", scenario_concurrent_writer),
                ("worker-survives-launcher", scenario_worker_survives_launcher),
                ("worker-survives-closed-stdout",
                 scenario_worker_survives_closed_stdout),
                ("watchdog", scenario_watchdog),
                ("status-query", scenario_status_query)):
            work = work_root / name
            work.mkdir()
            print("--- scenario: %s" % name, flush=True)
            scenario(work)
    finally:
        shutil.rmtree(work_root, ignore_errors=True)
    print("STAGE-B-LAB: PASS (%d checks)" % PASSED)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
