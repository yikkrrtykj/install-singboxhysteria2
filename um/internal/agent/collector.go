// Package agent implements the shared UM-B3 node runtime used by both the Linux
// VPS agent and the Windows terminal agent. Platform packages provide a
// Collector that produces frozen-contract report bodies; this package owns the
// identity, boot/sequence state, spool, recovery, HTTP transport, config,
// rotation and fail-closed lifecycle.
package agent

import (
	"context"
	"errors"
)

// ErrUnsupported is returned by a collector for a report kind the platform does
// not implement (for example Windows metrics v1 remains deferred).
var ErrUnsupported = errors.New("agent: report kind not supported on this platform")

// HostInfo is the frozen host object carried by Linux/Windows report bodies.
type HostInfo struct {
	OS     string
	Kernel string
	Arch   string
}

// InboundTag is one center-authorized expected inbound tag.
type InboundTag struct {
	InboundTag string
	Kind       string
}

// CollectConfig is the center-managed collection authorization snapshot handed
// to a platform collector. Sources use the frozen six keys.
type CollectConfig struct {
	ConfigVersion int
	Cadence       int
	Sources       map[string]bool
	ExpectedTags  []InboundTag
	DeviceSalt    string
}

// ReportContext contains the immutable identity/timestamp inputs for one report
// body. ReportID is generated by the runtime and must be embedded in the body.
type ReportContext struct {
	ReportID    string
	CollectedAt int64
	Host        HostInfo
	Config      CollectConfig
}

// Collector produces already-contract-valid report bodies. Implementations must
// be read-only with respect to the observed systems and must report honest
// unavailable/unknown data when a source cannot be observed.
type Collector interface {
	Snapshot(ctx context.Context, rc ReportContext) ([]byte, error)
	Metrics(ctx context.Context, rc ReportContext) ([]byte, error)
	Events(ctx context.Context, rc ReportContext) ([]byte, error)
}
